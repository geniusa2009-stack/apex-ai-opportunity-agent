import logging
import os
import tempfile
from pathlib import Path

from fastapi import APIRouter, File, Form, HTTPException, UploadFile, status
from pydantic import BaseModel, Field

from app.api.deps import CurrentUser
from app.services.voice_coach import voice_coach_gateway

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/voice-interview/evaluate", tags=["voice-coach"])

# Same allowed-set + size-guard pattern as advanced.py's document upload
# (Step 3.4), sized for audio instead of images. 25MB matches Groq's
# free-tier speech-to-text limit (see app/core/config.py's
# groq_whisper_model note) -- files larger than that would fail at Groq
# regardless of what this endpoint allows, so there's no point accepting
# them here.
_ALLOWED_CONTENT_TYPES = {
    "audio/mpeg",
    "audio/mp3",
    "audio/wav",
    "audio/x-wav",
    "audio/webm",
    "audio/mp4",
    "audio/m4a",
    "audio/x-m4a",
    "audio/ogg",
}
_MAX_FILE_SIZE_BYTES = 25 * 1024 * 1024  # 25 MB


class VoiceEvaluationResponse(BaseModel):
    transcribed_text: str = Field(
        description="The transcript produced by Whisper, echoed back "
        "as-is -- not regenerated by the evaluation LLM call, so it "
        "can't drift from what was actually transcribed."
    )
    content_score: int
    confidence_feedback: str
    improvement_tips: list[str]


@router.post("", response_model=VoiceEvaluationResponse)
async def evaluate_voice_interview_answer(
    current_user: CurrentUser,
    interview_question: str = Form(..., min_length=1, max_length=1000),
    file: UploadFile = File(..., description="An audio recording of the spoken answer."),
) -> VoiceEvaluationResponse:
    if file.content_type not in _ALLOWED_CONTENT_TYPES:
        raise HTTPException(
            status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            detail=(
                f"Unsupported file type {file.content_type!r}. "
                f"Accepted: {', '.join(sorted(_ALLOWED_CONTENT_TYPES))}."
            ),
        )

    audio_bytes = await file.read()
    if not audio_bytes:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Uploaded file is empty.")
    if len(audio_bytes) > _MAX_FILE_SIZE_BYTES:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail=f"File too large -- max {_MAX_FILE_SIZE_BYTES // (1024 * 1024)}MB "
            "(Groq's free-tier speech-to-text limit).",
        )

    # Preserve the original suffix (.wav/.mp3/etc.) so Groq's API has a
    # hint about the audio format from the filename, same as a real
    # client upload would provide -- `delete=False` because the file
    # needs to be closed (so Groq's client can open/read it by path)
    # before this endpoint reads it; cleanup happens explicitly in the
    # `finally` block below instead of relying on the context manager's
    # auto-delete-on-close behavior.
    suffix = Path(file.filename or "").suffix or ".wav"
    tmp = tempfile.NamedTemporaryFile(suffix=suffix, delete=False)
    tmp_path = tmp.name
    try:
        tmp.write(audio_bytes)
        tmp.close()

        try:
            transcribed_text = await voice_coach_gateway.transcribe_audio(tmp_path)
        except Exception:
            logger.exception("Audio transcription failed for user %s", current_user.id)
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Audio transcription is temporarily unavailable.",
            )

        try:
            evaluation = await voice_coach_gateway.evaluate_spoken_answer(
                transcribed_text, interview_question
            )
        except Exception:
            logger.exception("Spoken answer evaluation failed for user %s", current_user.id)
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Spoken answer evaluation is temporarily unavailable.",
            )
    finally:
        # Guaranteed cleanup regardless of success, an HTTPException
        # raised above, or any other exception -- the temp file never
        # survives this request either way.
        os.remove(tmp_path)

    return VoiceEvaluationResponse(
        transcribed_text=transcribed_text,
        content_score=evaluation.content_score,
        confidence_feedback=evaluation.confidence_feedback,
        improvement_tips=evaluation.improvement_tips,
    )
